"""Profile the raw IndPenSim data and write docs/DATA_PROFILE.md.

Run: uv run python -m kairos_ml.data.inspect
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from kairos_ml.data.load import (
    find_raw_csv,
    find_statistics_csv,
    is_raman_column,
    load_process_frame,
    read_header,
)
from kairos_ml.data.schema import BY_KEY

DOC_PATH = Path("docs/DATA_PROFILE.md")


def batch_summary(df: pd.DataFrame) -> pd.DataFrame:
    g = df.groupby("batch_id", sort=True)
    last = g.last()
    summary = pd.DataFrame(
        {
            "rows": g.size(),
            "t_end_h": g["time_h"].max(),
            "dt_h": g["time_h"].apply(lambda t: t.diff().median()),
            "control_ref": last["control_ref"],
            "pat_ref": last["pat_ref"],
            "fault_ref": last["fault_ref"],
            "fault_rows": g["fault_flag"].apply(lambda s: int((s != 0).sum())),
            "fault_onset_h": g.apply(lambda b: b.loc[b["fault_flag"] != 0, "time_h"].min()),
            "final_P_gl": last["penicillin_gl"],
            "final_V_l": last["volume_l"],
        }
    )
    summary["final_PV_kg"] = summary["final_P_gl"] * summary["final_V_l"] / 1000.0
    summary.index = summary.index.astype(int)
    summary.index.name = "batch"
    return summary


def profile() -> str:
    csv_path = find_raw_csv()
    header = read_header(csv_path)
    raman = [c for c in header if is_raman_column(c)]
    df = load_process_frame(csv_path)
    summary = batch_summary(df)

    lines: list[str] = ["# IndPenSim data profile", ""]
    lines += [
        "Generated by `uv run python -m kairos_ml.data.inspect`. Do not edit by hand.",
        "",
        f"- Source file: `{csv_path.name}` ({csv_path.stat().st_size / 1e9:.2f} GB)",
        f"- Rows: {len(df):,}",
        f"- Columns: {len(header):,} (process: {len(header) - len(raman)}, Raman: {len(raman)})",
        f"- Raman wavenumber range: {raman[0]} .. {raman[-1]}" if raman else "- No Raman columns",
        f"- Batches: {summary.shape[0]}",
        f"- Header quirk: the PAT_ref label has unquoted commas (header has 2 extra fields); repaired in `load.py`.",
        "",
        "## Process columns (canonical keys)",
        "",
        "| Key | Raw label | Unit | Kind | dtype | missing % | min | max | n unique |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for key in df.columns:
        s = df[key]
        col = BY_KEY[key]
        lines.append(
            f"| `{key}` | {col.raw} | {col.unit} | {col.kind} | {s.dtype} | "
            f"{100 * s.isna().mean():.1f} | {s.min():.4g} | {s.max():.4g} | {s.nunique()} |"
        )

    lines += ["", "## Groups", ""]
    for name, grp in summary.groupby(["control_ref", "pat_ref", "fault_ref"]):
        ids = grp.index.tolist()
        lines.append(
            f"- control_ref={name[0]}, pat_ref={name[1]}, fault_ref={name[2]}: "
            f"{len(ids)} batches ({ids[0]}..{ids[-1]}), final P*V median "
            f"{grp['final_PV_kg'].median():.0f} kg"
        )

    stats_path = find_statistics_csv()
    if stats_path is not None:
        stats = pd.read_csv(stats_path)
        lines += ["", f"## Published batch statistics (`{stats_path.name}`)", ""]
        lines += [f"- Columns: {', '.join(f'`{c}`' for c in stats.columns)}"]
        lines += [f"- Rows: {len(stats)}"]

    lines += ["", "## Per-batch summary", "", *_markdown_table(summary)]
    return "\n".join(lines) + "\n"


def _markdown_table(frame: pd.DataFrame) -> list[str]:
    cols = [str(frame.index.name or "batch"), *map(str, frame.columns)]
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for idx, row in frame.iterrows():
        cells = [str(idx)] + [f"{v:.4g}" if isinstance(v, float) else str(v) for v in row]
        out.append("| " + " | ".join(cells) + " |")
    return out


def main() -> None:
    text = profile()
    DOC_PATH.parent.mkdir(parents=True, exist_ok=True)
    DOC_PATH.write_text(text, encoding="utf-8")
    print(text[:6000])


if __name__ == "__main__":
    main()
