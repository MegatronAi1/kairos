// Generate platform tokens from design/tokens.json (single source of truth).
//   web/src/styles/tokens.css        CSS custom properties
//   web/src/styles/tokens.preset.cjs Tailwind preset
//   mobile/lib/core/theme/tokens.dart Dart constants
// Zero dependencies (see docs/DECISIONS.md: replaces Style Dictionary).
// Run: node design/build-tokens.mjs

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(join(root, "design/tokens.json"), "utf8"));
const HEADER = "Generated by design/build-tokens.mjs from design/tokens.json. Do not edit.";

/** Flatten {a:{b:{value}}} into [[["a","b"], value], ...]. */
function flatten(node, path = []) {
  if (node && typeof node === "object" && "value" in node) return [[path, node.value]];
  return Object.entries(node).flatMap(([k, v]) => flatten(v, [...path, k]));
}
const flat = flatten(tokens);

function write(rel, text) {
  const file = join(root, rel);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
  console.log(`wrote ${rel}`);
}

const isPx = (path) => ["size", "space", "radius"].some((p) => path.includes(p));
const cssValue = (path, v) =>
  isPx(path) ? `${v}px` : path[0] === "motion" && path[1] === "duration" ? `${v}ms` : v;

// --- CSS ---------------------------------------------------------------
const cssVars = flat.map(([p, v]) => `  --${p.join("-")}: ${cssValue(p, v)};`).join("\n");
write("web/src/styles/tokens.css", `/* ${HEADER} */\n:root {\n${cssVars}\n}\n`);

// --- Tailwind preset -----------------------------------------------------
const group = (prefix) =>
  Object.fromEntries(
    flat
      .filter(([p]) => p.slice(0, prefix.length).join("-") === prefix.join("-"))
      .map(([p]) => [p.slice(prefix.length).join("-"), `var(--${p.join("-")})`]),
  );
const preset = {
  theme: {
    extend: {
      colors: group(["color"]),
      fontFamily: { ui: ["var(--font-family-ui)"], mono: ["var(--font-family-mono)"] },
      fontSize: group(["font", "size"]),
      spacing: group(["space"]),
      borderRadius: group(["radius"]),
      transitionDuration: group(["motion", "duration"]),
      transitionTimingFunction: { standard: "var(--motion-easing-standard)" },
    },
  },
};
write(
  "web/src/styles/tokens.preset.cjs",
  `// ${HEADER}\nmodule.exports = ${JSON.stringify(preset, null, 2)};\n`,
);

// --- Dart ----------------------------------------------------------------
const camel = (parts) =>
  parts
    .map((s, i) => {
      const w = /^\d/.test(s) ? `x${s}` : s;
      return i === 0 ? w : w[0].toUpperCase() + w.slice(1);
    })
    .join("");
const dartColor = (hex) => {
  const h = hex.replace("#", "");
  const rgb = h.slice(0, 6);
  const alpha = h.length === 8 ? h.slice(6, 8) : "FF";
  return `Color(0x${(alpha + rgb).toUpperCase()})`;
};

const dart = [`// ${HEADER}`, "// ignore_for_file: public_member_api_docs", "", "import 'package:flutter/widgets.dart';", ""];
dart.push("abstract final class KColors {");
for (const [p, v] of flat.filter(([p]) => p[0] === "color")) {
  dart.push(`  static const ${camel(p.slice(1))} = ${dartColor(v)};`);
}
dart.push("}", "", "abstract final class KSize {");
for (const [p, v] of flat.filter(([p]) => p[0] === "font" && p[1] === "size")) {
  dart.push(`  static const double ${camel(p.slice(2))} = ${v};`);
}
dart.push("}", "", "abstract final class KSpace {");
for (const [p, v] of flat.filter(([p]) => p[0] === "space")) {
  dart.push(`  static const double s${p[1]} = ${v};`);
}
dart.push("}", "", "abstract final class KRadius {");
for (const [p, v] of flat.filter(([p]) => p[0] === "radius")) {
  dart.push(`  static const double ${camel(p.slice(1))} = ${v};`);
}
dart.push("}", "", "abstract final class KMotion {");
for (const [p, v] of flat.filter(([p]) => p[0] === "motion" && p[1] === "duration")) {
  dart.push(`  static const ${camel(p.slice(2))} = Duration(milliseconds: ${v});`);
}
const ease = flat.find(([p]) => p.join(".") === "motion.easing.standard")[1];
const [a, b, c, d] = ease.match(/[\d.]+/g);
dart.push(`  static const standard = Cubic(${a}, ${b}, ${c}, ${d});`);
dart.push("}", "", "abstract final class KFont {");
dart.push("  static const ui = 'Inter';", "  static const mono = 'JetBrainsMono';", "}", "");
write("mobile/lib/core/theme/tokens.dart", dart.join("\n"));
